def assert_bank_ok(cases: list[dict] | None = None) -> None:
    rows = cases if cases is not None else load_cases()
    ids = [c["id"] for c in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate case ids")
    seen_kinds = {c["kind"] for c in rows}
    if seen_kinds != set(KINDS):
        raise ValueError(f"missing kinds: {set(KINDS) - seen_kinds}")
    for case in rows:
        if case["training_eligible"] is not False:
            raise ValueError(f"{case['id']} must be training_eligible false")
        if case["answer"] not in case["options"]:
            raise ValueError(f"{case['id']} answer missing")
