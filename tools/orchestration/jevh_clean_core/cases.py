"""Atomic clean-core cases JEV-H is supposed to own.

Each answer is forced and independently establishable from the stated facts.
No TOO_HARD / escalate option. No game-design trivia.
training_eligible is always false: this bank is diagnostic.
"""

from __future__ import annotations

KINDS = (
    "source_stale",
    "permission_valid",
    "action_reversible",
    "owner",
    "human_approval",
    "canonical_contradicted",
    "repair_urgent",
    "event_causally_valid",
)

FORBIDDEN_OPTIONS = frozenset(
    {
        "too_hard",
        "too-hard",
        "escalate",
        "escalated",
        "unknown",
        "idk",
        "n/a",
        "skip",
    }
)


def _case(
    cid: str,
    kind: str,
    family: str,
    question: str,
    options: list[str],
    answer: str,
    context: str,
    why: str,
) -> dict:
    if kind not in KINDS:
        raise ValueError(f"unknown kind {kind}")
    if len(options) < 2:
        raise ValueError(f"{cid} needs at least two options")
    if answer not in options:
        raise ValueError(f"{cid} answer {answer!r} not in options")
    lowered = [o.strip().lower() for o in options]
    if any(o in FORBIDDEN_OPTIONS for o in lowered):
        raise ValueError(f"{cid} has a forbidden option")
    if len(set(options)) != len(options):
        raise ValueError(f"{cid} has duplicate options")
    return {
        "id": cid,
        "kind": kind,
        "family": family,
        "question": question,
        "options": list(options),
        "answer": answer,
        "context": context,
        "why": why,
        "training_eligible": False,
        "bucket": "CANARY-EVAL",
    }


